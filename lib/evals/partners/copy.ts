export const PARTNER_COPY = { en, es } as const;

export function partnerCopy(locale: "en" | "es") {
  const table: Record<PartnerCopyKey, string> = locale === "es" ? es : en;
  const t = (key: PartnerCopyKey) => table[key];
  const tv = (key: PartnerCopyKey, values: Record<string, string | number>) =>
    table[key].replace(/\{(\w+)\}/g, (match, name: string) => (name in values ? String(values[name]) : match));
  return { t, tv };
}

import { z } from "zod";
import { familyFingerprint } from "./workflow";
import { contextProfileSchema, type ContextProfile } from "./context";
import { withContentHash } from "../contracts/hashing";
import { languageSchema } from "../contracts/primitives";

const generatedCase = z.strictObject({
  question: z.string().trim().min(8).max(2000),
  expected: z.string().trim().min(1).max(2000),
  sourceRevisionId: z.uuid(),
  anchorId: z.uuid(),
  supportingQuote: z.string().trim().min(8).max(1200),
  severity: z.enum(["low", "medium", "high", "critical"]),
  difficulty: z.enum(["routine", "advanced", "challenge"]),
});
const generatedDraft = z.strictObject({ cases: z.array(generatedCase).min(1).max(20) });

export type AutoDraftCase = z.infer<typeof generatedCase>;
export type RejectedAutoDraftCase = { index: number; reasonCode: string };

function normalized(text: string) {
  return text.normalize("NFC").replace(/\s+/gu, " ").trim();
}

/**
 * Validate model proposals against exact extracted evidence before converting
 * them to CEF. This is a provenance/answer-support gate, not human review.
 */
export function validateAutogeneratedDraft(value: unknown, anchors: Map<string, string>): { cases: AutoDraftCase[]; rejectedCases: RejectedAutoDraftCase[] } {
  const parsed = generatedDraft.parse(value);
  const families = new Set<string>();
  const cases: AutoDraftCase[] = [];
  const rejectedCases: RejectedAutoDraftCase[] = [];
  for (const [index, item] of parsed.cases.entries()) {
    const excerpt = anchors.get(`${item.sourceRevisionId}:${item.anchorId}`);
    let reasonCode: string | undefined;
    if (!excerpt) reasonCode = "source_anchor_missing";
    else if (!normalized(excerpt).includes(normalized(item.supportingQuote))) reasonCode = "supporting_quote_missing";
    else if (!normalized(item.supportingQuote).toLocaleLowerCase().includes(normalized(item.expected).toLocaleLowerCase())) reasonCode = "answer_not_supported_by_quote";
    const family = familyFingerprint(item.question);
    if (!reasonCode && families.has(family)) reasonCode = "duplicate_question_family";
    if (reasonCode) {
      rejectedCases.push({ index: index + 1, reasonCode });
      continue;
    }
    families.add(family);
    cases.push(item);
  }
  if (!cases.length) throw new Error(rejectedCases[0]?.reasonCode ?? "no_source_grounded_cases");
  return { cases, rejectedCases };
}

const citation = z.strictObject({
  sourceRevisionId: z.uuid(),
  anchorId: z.uuid(),
  quote: z.string().trim().min(8).max(1200),
});
const profileField = z.strictObject({
  value: z.string().trim().min(1).max(2000).nullable(),
  confidence: z.number().min(0).max(1),
  citations: z.array(citation).max(20),
});
const profileListField = z.strictObject({
  values: z.array(z.string().trim().min(1).max(500)).max(50),
  confidence: z.number().min(0).max(1),
  citations: z.array(citation).max(20),
});
const generatedQuestionField = z.enum(["purpose", "intendedUsers", "tasks", "languages", "jurisdiction", "asOf", "businessBoundaries", "supportedCapabilities", "materialRisks", "allowedActions", "tools"]);
export const autogeneratedProfileSchema = z.strictObject({
  purpose: profileField,
  intendedUsers: profileListField,
  tasks: profileListField,
  languages: profileListField,
  jurisdiction: profileField,
  asOf: profileField,
  businessBoundaries: profileListField,
  supportedCapabilities: profileListField,
  materialRisks: profileListField,
  allowedActions: profileListField,
  tools: profileListField,
  criticalQuestions: z.array(z.strictObject({ field: generatedQuestionField, question: z.string().min(1).max(1000) })).max(50),
});
export type AutogeneratedProfile = z.infer<typeof autogeneratedProfileSchema>;

export function normalizeLanguageTags(values: string[]): string[] {
  const normalized = values.map((value) => {
    const canonical = Intl.getCanonicalLocales(value.trim())[0];
    if (!canonical || !languageSchema.safeParse(canonical).success) throw new Error("context_language_invalid_bcp47");
    const primary = canonical.split("-")[0];
    const displayName = new Intl.DisplayNames(["en"], { type: "language" }).of(canonical);
    if (primary.length > 3 && displayName?.toLocaleLowerCase("en") === primary.toLocaleLowerCase("en"))
      throw new Error("context_language_invalid_bcp47");
    return canonical;
  });
  return [...new Set(normalized)];
}

export function parseLanguageAnswer(answer: string): string[] {
  const values = answer.split(/[\n,;]/u).map((value) => value.trim()).filter(Boolean);
  if (!values.length) throw new Error("context_answer_invalid_language");
  try { return normalizeLanguageTags(values); }
  catch { throw new Error("context_answer_invalid_language"); }
}

export function validateAutogeneratedProfile(value: unknown, anchors: Map<string, string>): AutogeneratedProfile {
  const parsed = autogeneratedProfileSchema.parse(value);
  parsed.languages.values = normalizeLanguageTags(parsed.languages.values);
  const fields = Object.entries(parsed).filter(([field]) => field !== "criticalQuestions");
  for (const [field, raw] of fields) {
    const item = raw as z.infer<typeof profileField> | z.infer<typeof profileListField>;
    const populated = "value" in item ? item.value !== null : item.values.length > 0;
    if (populated && !item.citations.length) throw new Error(`profile_field_uncited:${field}`);
    for (const ref of item.citations) {
      const excerpt = anchors.get(`${ref.sourceRevisionId}:${ref.anchorId}`);
      if (!excerpt) throw new Error("source_anchor_missing");
      if (!normalized(excerpt).includes(normalized(ref.quote))) throw new Error("profile_quote_missing");
    }
  }
  return parsed;
}


export type ConfirmedContextAnswer = {
  id: string;
  field: string;
  question: string;
  answer: string;
};

/** Keep the persisted one-question-per-field contract while retaining model-specific clarifications. */
export function mergeAutogeneratedQuestions(
  baseline: ContextProfile["unanswered_questions"],
  generated: Array<{ field: string; question: string }>,
): ContextProfile["unanswered_questions"] {
  const generatedFields = new Set(generated.map((item) => item.field));
  const grouped = new Map<string, { questions: string[]; critical: boolean }>();
  const add = (field: string, question: string, critical: boolean) => {
    const current = grouped.get(field) ?? { questions: [], critical: false };
    if (!current.questions.includes(question)) current.questions.push(question);
    current.critical ||= critical;
    grouped.set(field, current);
  };
  for (const item of baseline) {
    if (!generatedFields.has(item.field)) add(item.field, item.question, item.critical);
  }
  for (const item of generated) add(item.field, item.question, true);
  return [...grouped].map(([field, item]) => ({
    field,
    question: item.questions.join(" Also: "),
    critical: item.critical,
  }));
}

/** Applies only answers for an open profile question and keeps them distinguishable from source evidence. */
export function resolveAutogeneratedContext(raw: unknown, answers: ConfirmedContextAnswer[]): ContextProfile {
  const profile = contextProfileSchema.parse(raw);
  const key = (field: string, question: string) => JSON.stringify([field, question]);
  const open = new Set(profile.unanswered_questions.map((item) => key(item.field, item.question)));
  const openFields = new Set(profile.unanswered_questions.map((item) => item.field));
  // The database intentionally stores one answer row per field. Older profiles could
  // contain differently-worded questions for the same field, so resolve those together.
  const applicable = answers.filter((item) => open.has(key(item.field, item.question)) || openFields.has(item.field));
  if (!applicable.length) throw new Error("context_answer_not_applicable");
  let resolved = { ...profile, confirmed_context: [...profile.confirmed_context] } as ContextProfile;
  const knownConfirmations = new Set(resolved.confirmed_context.map((item) => item.confirmation_id));
  for (const item of applicable) {
    const answer = item.answer.trim();
    if (!answer || answer.length > 2000) throw new Error("context_answer_invalid");
    const basis = "operator_confirmation:" + item.id;
    if (item.field === "purpose") resolved.purpose = { value: answer, confidence: 1, basis: [basis] };
    else if (item.field === "jurisdiction") resolved.jurisdiction = { value: answer, confidence: 1, basis: [basis] };
    else if (item.field === "as_of") {
      const timestamp = /^\d{4}-\d{2}-\d{2}$/.test(answer) ? answer + "T00:00:00.000Z" : answer;
      const date = new Date(timestamp);
      if (Number.isNaN(date.getTime()) || !/^\d{4}-\d{2}-\d{2}(?:T.*(?:Z|[+-]\d{2}:?\d{2}))?$/.test(timestamp))
        throw new Error("context_answer_invalid_date");
      resolved.as_of = date.toISOString();
      resolved.field_confidence = { ...resolved.field_confidence, as_of: 1 };
    } else if (["intended_users", "tasks", "languages", "business_boundaries", "supported_capabilities", "material_risks", "allowed_actions", "tool_descriptions"].includes(item.field)) {
      const values = answer.split(/[\n,;]/u).map((value) => value.trim()).filter(Boolean);
      if (!values.length) throw new Error("context_answer_invalid");
      const field = item.field;
      if (field === "intended_users") resolved.intended_users = values;
      else if (field === "tasks") resolved.tasks = values;
      else if (field === "languages") resolved.languages = parseLanguageAnswer(answer);
      else if (field === "business_boundaries") resolved.business_boundaries = values;
      else if (field === "supported_capabilities") resolved.supported_capabilities = values;
      else if (field === "material_risks") resolved.material_risks = values;
      else if (field === "allowed_actions") resolved.allowed_actions = values;
      else resolved.tool_descriptions = values;
      resolved.field_confidence = { ...resolved.field_confidence, [field]: 1 };
    }
    if (!knownConfirmations.has(item.id)) {
      resolved.confirmed_context.push({ confirmation_id: item.id, field: item.field, question: item.question, answer });
      knownConfirmations.add(item.id);
    }
  }
  const resolvedFields = new Set(applicable.map((item) => item.field));
  return contextProfileSchema.parse(withContentHash({
    ...resolved,
    unanswered_questions: resolved.unanswered_questions.filter((item) => !resolvedFields.has(item.field)),
  }));
}

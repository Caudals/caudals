/** Largest automatic test set; bigger sets are drafted in rounds. */
export const MAX_GENERATED_CASES = 200;
/** Cases asked of the model per drafting round: the DGX's 8,192-token output fits about a dozen. */
const roundSize = (route: Pick<GenerationRoute, "adapter">) => (route.adapter === "dgx" ? 12 : 20);
/** Rounds allowed for a target: enough for every case plus slack for rounds that yield fewer. */
const maxRounds = (target: number) => Math.min(40, Math.ceil(target / 10) + 2);
/** At most this many questions may pause preparation; the rest are answered from the sources. */
const MAX_BLOCKING_QUESTIONS = 3;

const startSchema = z.strictObject({
  sourceRevisionIds: z.array(z.uuid()).min(1).max(21),
  title: z.string().trim().min(1).max(200),
  executionMode: z.enum(["deployed_system", "controlled_model", "imported_responses"]),
  promptRevision: z.string().min(1).max(100),
  maxCases: z.number().int().min(1).max(MAX_GENERATED_CASES).default(10),
  complexity: complexitySchema.default("balanced"),
  /** Interface language: context questions are written in it. */
  locale: z.enum(["en", "es"]).default("en"),
});
type GenerationRoute = ModelRoute;
/**
 * The DGX serves generation at roughly 15 tokens/s within an 8,192-token
 * allowance: reasoning first would spend the whole allowance (about nine
 * minutes) before the reasoning-off retry. Commercial APIs are fast enough to
 * reason inside a bounded share first.
 */
const generationReasoning = (route: Pick<GenerationRoute, "adapter">) => (route.adapter === "dgx" ? "off" : "bounded");
const generationOutputCap = (route: Pick<GenerationRoute, "adapter" | "tpm">) => Math.min(route.adapter === "dgx" ? 8192 : 24576, Math.floor(route.tpm / 2));

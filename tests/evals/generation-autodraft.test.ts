import { describe, expect, it } from "vitest";
import { validateAutogeneratedDraft } from "../../lib/evals/generation/auto-draft";
import { withContentHash } from "../../lib/evals/contracts/hashing";
import { boundedOutputTokens } from "../../lib/evals/providers/contracts";

const sourceId = "11111111-1111-4111-8111-111111111111";
const anchorId = "22222222-2222-4222-8222-222222222222";
const anchors = new Map([[`${sourceId}:${anchorId}`, "Refunds are available within 30 days of purchase."]]);
const draft = { cases: [{
  question: "For a purchase of EUR 50, within how many days can a customer request a refund?",
  expected: "30 days",
  sourceRevisionId: sourceId,
  anchorId,
  supportingQuote: "Refunds are available within 30 days of purchase.",
  severity: "medium",
  difficulty: "routine",
}] };

describe("DGX generation context bounds", () => {
  it("reserves prompt bytes and template headroom before selecting the output limit", () => {
    const messages = [{ role: "system" as const, content: "x".repeat(4000) }];
    const bytes = Buffer.byteLength(JSON.stringify(messages), "utf8");
    const output = boundedOutputTokens(messages, 8192, 4096);
    expect(output).toBe(Math.min(4096, 8192 - bytes - 1024));
    expect(bytes + 1024 + output).toBeLessThanOrEqual(8192);
    expect(boundedOutputTokens(messages, 8192, 4096, 768)).toBe(768);
  });

  it("rejects prompts that leave too little room for a useful bounded response", () => {
    expect(() => boundedOutputTokens([{ role: "user", content: "x".repeat(7200) }], 8192, 4096))
      .toThrow("context_bound_exceeded");
  });
});

describe("DGX generated case grounding", () => {
  it("accepts only source-linked answers whose supporting quote is present in the cited anchor", () => {
    const parsed = validateAutogeneratedDraft(draft, anchors);
    expect(parsed.cases).toHaveLength(1);
    expect(parsed.cases[0]).toMatchObject({ question: draft.cases[0].question, expected: "30 days", anchorId });
  });

  it("rejects a generated answer that is not supported by its cited excerpt", () => {
    expect(() => validateAutogeneratedDraft({ cases: [{ ...draft.cases[0], expected: "90 days" }] }, anchors))
      .toThrow("answer_not_supported_by_quote");
  });

  it("rejects missing or fabricated source anchors", () => {
    expect(() => validateAutogeneratedDraft({ cases: [{ ...draft.cases[0], anchorId: "33333333-3333-4333-8333-333333333333" }] }, anchors))
      .toThrow("source_anchor_missing");
    expect(() => validateAutogeneratedDraft({ cases: [{ ...draft.cases[0], supportingQuote: "Refunds are available within 90 days." }] }, anchors))
      .toThrow("supporting_quote_missing");
  });

  it("rejects near-duplicate generated question families", () => {
    const duplicate = { ...draft.cases[0], question: "For a purchase of EUR 10, within how many days can a customer request a refund?" };
    expect(() => validateAutogeneratedDraft({ cases: [draft.cases[0], duplicate] }, anchors))
      .toThrow("duplicate_question_family");
  });
});

const profile = {
  purpose: { value: "Answer refund policy questions", confidence: 0.9, citations: [{ sourceRevisionId: sourceId, anchorId, quote: "Refunds are available within 30 days of purchase." }] },
  intendedUsers: { values: ["Customers"], confidence: 0.8, citations: [{ sourceRevisionId: sourceId, anchorId, quote: "Refunds are available within 30 days of purchase." }] },
  tasks: { values: ["Explain refund eligibility"], confidence: 0.9, citations: [{ sourceRevisionId: sourceId, anchorId, quote: "Refunds are available within 30 days of purchase." }] },
  languages: { values: ["en"], confidence: 0.9, citations: [{ sourceRevisionId: sourceId, anchorId, quote: "Refunds are available within 30 days of purchase." }] },
  jurisdiction: { value: null, confidence: 0, citations: [] },
  asOf: { value: null, confidence: 0, citations: [] },
  businessBoundaries: { values: [], confidence: 0, citations: [] },
  supportedCapabilities: { values: ["text"], confidence: 0.9, citations: [{ sourceRevisionId: sourceId, anchorId, quote: "Refunds are available within 30 days of purchase." }] },
  materialRisks: { values: [], confidence: 0, citations: [] },
  allowedActions: { values: [], confidence: 0, citations: [] },
  tools: { values: [], confidence: 0, citations: [] },
  criticalQuestions: [],
};

describe("DGX inferred context profile", () => {
  it("normalizes BCP 47 language tags and rejects display names that cannot be stored", async () => {
    const { normalizeLanguageTags, parseLanguageAnswer, validateAutogeneratedProfile } = await import("../../lib/evals/generation/auto-draft");
    expect(normalizeLanguageTags(["EN-us", "es-es", "en-US"])).toEqual(["en-US", "es-ES"]);
    expect(parseLanguageAnswer("en, es-ES")).toEqual(["en", "es-ES"]);
    expect(() => parseLanguageAnswer("English and Spanish")).toThrow("context_answer_invalid_language");
    expect(() => validateAutogeneratedProfile({ ...profile, languages: { ...profile.languages, values: ["English"] } }, anchors))
      .toThrow("context_language_invalid_bcp47");
  });

  it("requires citations for inferred context and verifies each cited quote", async () => {
    const { validateAutogeneratedProfile } = await import("../../lib/evals/generation/auto-draft");
    expect(validateAutogeneratedProfile(profile, anchors).tasks.values).toEqual(["Explain refund eligibility"]);
    expect(() => validateAutogeneratedProfile({ ...profile, purpose: { ...profile.purpose, citations: [] } }, anchors))
      .toThrow("profile_field_uncited:purpose");
    expect(() => validateAutogeneratedProfile({ ...profile, tasks: { ...profile.tasks, citations: [{ sourceRevisionId: sourceId, anchorId, quote: "There are 60 days for refunds." }] } }, anchors))
      .toThrow("profile_quote_missing");
    expect(() => validateAutogeneratedProfile({ ...profile, criticalQuestions: [{ field: "unmapped", question: "Which?" }] }, anchors))
      .toThrow();
  });
});


describe("confirmed context answers", () => {
  it("merges duplicate generated questions by field and resolves legacy duplicate wording from one stored answer", async () => {
    const { mergeAutogeneratedQuestions, resolveAutogeneratedContext } = await import("../../lib/evals/generation/auto-draft");
    const questions = mergeAutogeneratedQuestions(
      [{ field: "tasks", question: "Which tasks should be tested?", critical: true }],
      [
        { field: "tasks", question: "How should the service fee be calculated?" },
        { field: "tasks", question: "How should the final total be rounded?" },
      ],
    );
    expect(questions).toEqual([{
      field: "tasks",
      question: "How should the service fee be calculated? Also: How should the final total be rounded?",
      critical: true,
    }]);

    const confirmationId = "33333333-3333-4333-8333-333333333333";
    const legacyProfile = withContentHash({
      schema_version: "1.0", evaluation_id: sourceId, purpose: { value: "Fee policy", confidence: 1, basis: [] },
      intended_users: [], tasks: [], business_boundaries: [], supported_capabilities: ["text"],
      source_hierarchy: [{ source_revision_id: sourceId, rank: 1, authority: "customer_supplied" }], languages: ["en"],
      jurisdiction: { value: null, confidence: 0, basis: [] }, as_of: null, material_risks: [], allowed_actions: [],
      tool_descriptions: [], field_confidence: {},
      unanswered_questions: [{ field: "tasks", question: "How should the service fee be calculated?", critical: true }],
      conflicts: [], confirmed_context: [{
        confirmation_id: confirmationId, field: "tasks", question: "How should the final total be rounded?",
        answer: "Add the fee before rounding and round once to two decimals.",
      }],
      prompt_revision: "test-v1", model_revision_id: null,
    });
    const recovered = resolveAutogeneratedContext(legacyProfile, [{
      id: confirmationId, field: "tasks", question: "How should the final total be rounded?",
      answer: "Add the fee before rounding and round once to two decimals.",
    }]);
    expect(recovered.unanswered_questions).toEqual([]);
    expect(recovered.tasks).toEqual(["Add the fee before rounding and round once to two decimals."]);
    expect(recovered.confirmed_context).toHaveLength(1);
  });

  it("resolves answered critical questions and preserves operator-provided scope", async () => {
    const { resolveAutogeneratedContext } = await import("../../lib/evals/generation/auto-draft");
    const profileWithQuestions = withContentHash({
      schema_version: "1.0",
      evaluation_id: sourceId,
      purpose: { value: null, confidence: 0, basis: [] },
      intended_users: [],
      tasks: ["Explain refund eligibility"],
      business_boundaries: [],
      supported_capabilities: ["text"],
      source_hierarchy: [{ source_revision_id: sourceId, rank: 1, authority: "customer_supplied" }],
      languages: ["en"],
      jurisdiction: { value: null, confidence: 0, basis: [] },
      as_of: null,
      material_risks: [],
      allowed_actions: [],
      tool_descriptions: [],
      field_confidence: {},
      unanswered_questions: [{ field: "purpose", question: "What should the system do?", critical: true }],
      conflicts: [],
      confirmed_context: [],
      prompt_revision: "test-v1",
      model_revision_id: null,
    });
    const resolved = resolveAutogeneratedContext(profileWithQuestions, [{
      id: "33333333-3333-4333-8333-333333333333",
      field: "purpose",
      question: "What should the system do?",
      answer: "Answer customer refund questions",
    }]);
    expect(resolved.purpose).toMatchObject({ value: "Answer customer refund questions", confidence: 1 });
    expect(resolved.unanswered_questions).toEqual([]);
    expect(resolved.confirmed_context).toEqual([{
      field: "purpose",
      question: "What should the system do?",
      answer: "Answer customer refund questions",
      confirmation_id: "33333333-3333-4333-8333-333333333333",
    }]);
    expect(resolved.content_hash).toMatch(/^[a-f0-9]{64}$/);
  });

  it("requires a valid ISO date when an as-of question is critical", async () => {
    const { resolveAutogeneratedContext } = await import("../../lib/evals/generation/auto-draft");
    const base = withContentHash({
      schema_version: "1.0", evaluation_id: sourceId, purpose: { value: "Tax help", confidence: 1, basis: [] },
      intended_users: [], tasks: ["tax advice"], business_boundaries: [], supported_capabilities: ["text"],
      source_hierarchy: [{ source_revision_id: sourceId, rank: 1, authority: "customer_supplied" }], languages: ["en"],
      jurisdiction: { value: null, confidence: 0, basis: [] }, as_of: null, material_risks: [], allowed_actions: [],
      tool_descriptions: [], field_confidence: {}, unanswered_questions: [{ field: "as_of", question: "Which date?", critical: true }],
      conflicts: [], confirmed_context: [], prompt_revision: "test-v1", model_revision_id: null,
    });
    expect(() => resolveAutogeneratedContext(base, [{
      id: "33333333-3333-4333-8333-333333333333", field: "as_of", question: "Which date?", answer: "last year",
    }])).toThrow("context_answer_invalid_date");
  });
});

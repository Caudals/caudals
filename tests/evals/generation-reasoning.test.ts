import { describe, expect, it } from "vitest";
import { normalizeContextAnswer, parseAsOfAnswer, resolveAutogeneratedContext } from "../../lib/evals/generation/auto-draft";
import { buildContextProfile } from "../../lib/evals/generation/context";
import { withContentHash } from "../../lib/evals/contracts/hashing";
import { EvalError, inputError } from "../../lib/evals/domain/errors";
import { invocationSchema } from "../../lib/evals/providers/contracts";
import { reasoningBudget, reasoningHint } from "../../lib/evals/providers/openai-compatible";

const dgx = (model_id: string) => ({ adapter: "dgx" as const, model_id });
const api = (model_id: string) => ({ adapter: "openai_compatible" as const, model_id });
const generator = { role: "generator" as const, probe: false };

describe("context answers people type", () => {
  it("accepts a year, a month, a day or a timestamp as the effective date", () => {
    expect(parseAsOfAnswer("2027")).toBe("2027-01-01T00:00:00.000Z");
    expect(parseAsOfAnswer("2027-3")).toBe("2027-03-01T00:00:00.000Z");
    expect(parseAsOfAnswer(" 2027-03-15 ")).toBe("2027-03-15T00:00:00.000Z");
    expect(parseAsOfAnswer("15/03/2027")).toBe("2027-03-15T00:00:00.000Z");
    expect(parseAsOfAnswer("2027-03-15T10:00:00+02:00")).toBe("2027-03-15T08:00:00.000Z");
  });

  it("rejects dates that do not exist or are not dates", () => {
    for (const value of ["2027-02-31", "tomorrow", "eu regulations", "27", "2027-13"]) expect(() => parseAsOfAnswer(value)).toThrow("context_answer_invalid_date");
  });

  it("normalizes answers before they are saved", () => {
    expect(normalizeContextAnswer("as_of", "2027")).toBe("2027-01-01");
    expect(normalizeContextAnswer("languages", "en, es-ES")).toBe("en, es-ES");
    expect(normalizeContextAnswer("jurisdiction", "  EU  ")).toBe("EU");
    expect(() => normalizeContextAnswer("tasks", "   ")).toThrow("context_answer_invalid");
  });

  it("resolves a year-only as-of answer instead of stopping preparation", () => {
    const built = buildContextProfile({ evaluationId: "e1", sources: [], promptRevision: "p1", modelRevisionId: "m1" });
    const question = "Which effective date should be used? Provide a date in YYYY-MM-DD format.";
    const profile = withContentHash({ ...built, unanswered_questions: [...built.unanswered_questions, { field: "as_of", question, critical: true }] });
    const resolved = resolveAutogeneratedContext(profile, [{ id: "a1", field: "as_of", question, answer: "2027" }]);
    expect(resolved.as_of).toBe("2027-01-01T00:00:00.000Z");
  });

  it("turns domain input codes into a 422 with guidance, not a generic 503", () => {
    const mapped = inputError(new Error("context_answer_invalid_date"));
    expect(mapped).toBeInstanceOf(EvalError);
    expect(mapped?.status).toBe(422);
    expect(mapped?.message).toMatch(/YYYY-MM-DD/);
    expect(inputError(new Error("something_else"))).toBeNull();
    expect(inputError(new EvalError("SCOPE_DENIED", 404))).toBeNull();
  });
});

describe("reasoning allowance for internal engine calls", () => {
  it("lets generation think inside an explicit share of the output allowance", () => {
    expect(reasoningBudget(16384)).toBe(6553);
    expect(reasoningBudget(40000)).toBe(8192);
    expect(reasoningBudget(512)).toBe(512);
    expect(reasoningHint(api("x/y:free"), "openrouter.ai", { ...generator, reasoning: "bounded", maxOutputTokens: 16384 })).toEqual({ reasoning: { max_tokens: 6553 } });
  });

  it("uses the model default on the DGX, where thinking flags can be rejected", () => {
    expect(reasoningHint(dgx("qwen3-coder:30b"), "10.0.0.2", { ...generator, reasoning: "bounded" })).toEqual({});
    expect(reasoningHint(dgx("bluehawana/deepseek-v4-flash:iq2_m"), "10.0.0.2", { ...generator, reasoning: "bounded" })).toEqual({});
    expect(reasoningHint(dgx("gpt-oss:20b"), "10.0.0.2", { ...generator, reasoning: "bounded" })).toEqual({ reasoning_effort: "low" });
  });

  it("switches reasoning off for the retry, except where a model cannot", () => {
    expect(reasoningHint(dgx("bluehawana/deepseek-v4-flash:iq2_m"), "10.0.0.2", { ...generator, reasoning: "off" })).toEqual({ reasoning_effort: "none" });
    expect(reasoningHint(dgx("gpt-oss:20b"), "10.0.0.2", { ...generator, reasoning: "off" })).toEqual({ reasoning_effort: "low" });
    expect(reasoningHint(api("z-ai/glm-5.3-flash"), "integrate.api.nvidia.com", { ...generator, reasoning: "off" })).toEqual({ reasoning_effort: "none" });
    expect(reasoningHint(api("x/y:free"), "openrouter.ai", { ...generator, reasoning: "off" })).toEqual({ reasoning: { enabled: false } });
  });

  it("keeps short grading calls lean and never touches target calls", () => {
    expect(reasoningHint(api("z-ai/glm-5.3-flash"), "integrate.api.nvidia.com", { role: "judge", probe: false })).toEqual({ reasoning_effort: "none" });
    expect(reasoningHint(api("x/y"), "openrouter.ai", { role: "judge", probe: false })).toEqual({ reasoning: { effort: "low" } });
    expect(reasoningHint(api("x/y"), "openrouter.ai", { role: "target", probe: false, reasoning: "off" })).toEqual({});
  });

  it("accepts the reasoning mode on a frozen invocation", () => {
    const base = { providerRevisionId: "11111111-1111-4111-8111-111111111111", priceRevisionId: "22222222-2222-4222-8222-222222222222", workspaceBudgetId: "33333333-3333-4333-8333-333333333333", runBudgetId: "44444444-4444-4444-8444-444444444444", role: "generator", dataClass: "customer_confidential", region: "external_api", routing: "approved_providers", approvedProviderIds: [], messages: [{ role: "user", content: "hi" }], maxOutputTokens: 1024 };
    expect(invocationSchema.parse({ ...base, reasoning: "off" }).reasoning).toBe("off");
    expect(invocationSchema.parse(base).reasoning).toBeUndefined();
    expect(() => invocationSchema.parse({ ...base, reasoning: "high" })).toThrow();
  });
});
